//! 局域网 P2P 传输层。
//!
//! 分工只有一句话：**Rust 只做「发现 + 搬运」，不认识任何聊天协议**。
//!
//! 帧里装的是一整段 TS 侧生成、并且已经加密好的 JSON，Rust 原样透传给前端。
//! 所以加密、发送序号、会话路由、离线队列全部留在 TS 里 —— 那里本来就有
//! 一份验过的实现，只有「怎么找到对方」和「怎么把字节送过去」是浏览器做不到的，
//! 那两件事才是这个模块存在的全部理由。
//!
//! 边界只有一条：`Vec<u8>` 进，`Vec<u8>` 出。改协议不用动 Rust。

pub mod discover;
pub mod frames;
pub mod link;
pub mod node;

/// 默认 UDP 发现端口。
///
/// 固定端口不是偷懒：防火墙规则、排查问题、文档描述都以它为准，
/// 每次随机端口会让「为什么连不上」变成一个不可复现的问题。
pub const DEFAULT_UDP_PORT: u16 = 47800;

/// 默认 TCP 数据端口。
pub const DEFAULT_TCP_PORT: u16 = 47800;
