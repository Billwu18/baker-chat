/**
 * 混合逻辑时钟（HLC）—— 给事件排序用的那个数。
 *
 * ## 问题
 *
 * 每条事件都要有一个能**全局比较**的时间。候选有三个，都不能直接用：
 *
 *   1. `Date.now()` —— 局域网里每台机器的表都不一样，差几秒很常见，
 *      差几个月（装完系统没同步过时间）也不稀奇。用墙上时钟排序，
 *      一台表慢的机器发的消息会永远压在别人的**旧消息**下面。
 *   2. 纯计数器（1、2、3…）—— 每个节点各自数，A 的第 5 条和 B 的第 5 条
 *      撞在一起，而且谁先谁后完全没法判断。
 *   3. Lamport 时钟 —— 能保证「因果序」，但和真实时间脱钩：
 *      数跑快了的节点会一直排在前面。
 *
 * HLC 把前两者的好处拼起来：**主序跟随物理时间，同一毫秒内用序号区分**。
 * 于是它既接近真实时间（人看着不舒服的顺序不会出现），又严格单调
 * （同一台机器上后发生的事件一定排在后面），而且收到别人的时间戳时
 * 会「追上去」，不会因为自己的表慢就落在后面。
 *
 * ## 编码
 *
 * 一个 `number`：`物理毫秒 * 1000 + 序号`，序号 0–999。
 *
 *     1770000000000 * 1000 + 0  =  1770000000000000
 *
 * `Number.MAX_SAFE_INTEGER` 是 9007199254740991（约 9.007e15），
 * 而 1770000000000 * 1000 = 1.77e15 —— 还剩 5 倍余量，
 * 够用到公元 2255 年。超了之后低位会开始丢失精度，
 * 也就是「同一毫秒内的顺序」先乱，而跨毫秒的顺序仍然正确；
 * 那是个可以接受的降级，不是崩坏。
 *
 * 为什么非要塞进一个 `number` 而不是 `{ms, seq}` 两个字段：
 * 事件排序、ID 比较、游标存储全都要比大小，一个数比两个字段简单得多，
 * 也不会出现「ms 相同但 seq 忘了比」这种写漏一次就再也查不出来的 bug。
 */

/**
 * 序号上限。一毫秒最多 1000 条 —— 局域网聊天不可能逼近，
 * 但真的到了就进位到下一毫秒，而不是让序号溢出污染高位。
 */
const SEQ_LIMIT = 1000

/** 取 `ts` 里的物理毫秒部分。只用于显示和调试，排序永远比整个 `ts`。 */
export function physicalMs(ts: number): number {
  return Math.floor(ts / SEQ_LIMIT)
}

/**
 * HLC 编码值 → **给消息用的毫秒数**（保留小数）。
 *
 * 为什么不直接 `physicalMs()`（取整）：那会把同 1 毫秒内的两条消息压成同一个
 * 时间戳，先后顺序就只剩 id 兜底 —— 而 id 是哈希，和发送先后**没有关系**。
 * 后果是同一毫秒里发的两条消息在界面上可能颠倒，而且两台机器各自按 id
 * 排出不同的顺序（折叠层的 `insertMessageSorted` 比的是 `(sentAt, id)`，
 * 而事件层比的是 `(ts, id)`，两者会不一致 —— 自检里「消息按时间升序」
 * 就是这么红的）。
 *
 * `ts / 1000` 恰好等于「毫秒 + 序号/1000」，和 `ts` **严格同序**，
 * 同时 `new Date(它)` 会按毫秒截断，显示仍然是对的。
 *
 * 精度：`ts` 最大约 9e15，除以 1000 之后是 9e12 量级，双精度在这个量级的
 * 间隔约 0.0005，小于 0.001（一个序号），所以相邻序号不会被压成同一个数。
 * 这个余量够用到下个世纪。
 */
export function tsToMillis(ts: number): number {
  return ts / SEQ_LIMIT
}

/** 把 `ts` 还原成 `Date`，给 UI 显示时间用。 */
export function tsToDate(ts: number): Date {
  return new Date(physicalMs(ts))
}

/**
 * 一台机器上的 HLC。
 *
 * 不是全局单例 —— 一个进程里同时存在多个（比如「接收循环」和「发送循环」
 * 各一个）会破坏单调性，所以正常用法是**整个节点共用一个实例**，
 * 通过 `log.ts` 传下去。做成类而不是模块级状态，是为了自测里能造
 * 任意初始状态的时钟，不必污染全局。
 */
export class HybridClock {
  /** 上一次发出的 `ts`（含序号的完整值）。 */
  private last = 0
  /** 上一次发出的**物理部分**，避免每次 tick 都要除一遍。 */
  private lastMs = 0
  /** 当前毫秒内已用掉的序号。 */
  private seq = 0

  /**
   * 从持久化的值恢复。
   *
   * 重点不是「恢复时间」，而是**恢复单调性**：进程重启后如果从 0 开始，
   * 新事件的 `ts` 会小于重启前的，于是自己刚发的消息在日志里排到了
   * 自己旧消息的前面。这在重放历史时会表现得非常怪（对话顺序颠倒），
   * 而且因为「重启才出现」，很容易被当成偶发问题放过去。
   *
   * 传进来的值比当前小（比如换了台机器、文件被回滚）就忽略 ——
   * 宁可让时钟停滞一会儿，也不能让它倒退。
   */
  restore(ts: number): void {
    if (!Number.isFinite(ts) || ts <= this.last) return
    this.last = ts
    this.lastMs = physicalMs(ts)
    this.seq = ts % SEQ_LIMIT
  }

  /** 当前值，给持久化用。 */
  peek(): number {
    return this.last
  }

  /**
   * 发一条新事件前拿时间戳。
   *
   * 三条规则，顺序不能换：
   *   1. 物理时间**前进**了 → 用新时间，序号归零；
   *   2. 没前进（同一毫秒内，或系统表被人往回拨了）→ 序号 +1；
   *   3. 序号用满 → 借一毫秒。
   */
  tick(now: number = Date.now()): number {
    if (now > this.lastMs) {
      this.lastMs = now
      this.seq = 0
    } else {
      this.seq += 1
      if (this.seq >= SEQ_LIMIT) {
        this.lastMs += 1
        this.seq = 0
      }
    }
    this.last = this.lastMs * SEQ_LIMIT + this.seq
    return this.last
  }

  /**
   * 收到一条别人的事件时调用。
   *
   * 这是 HLC 相比纯计数器**唯一**真正多出来的能力：知道「世界上还有别的
   * 时钟走到这儿了」，于是本地时钟至少推到同样的位置。效果是 ——
   *
   *   - 一台表慢的机器，收到快机器的消息后，它接下来发的事件**排在
   *     那条消息之后**（因果正确），而不是因为自己表慢就排到前面；
   *   - 两台机器互相收发之后，它们的时间戳会收敛到一起，
   *     最终排序看起来就像一台机器发的。
   *
   * 不做这一步也「能跑」：只是当某台机器关掉一会儿再打开、或者
   * 双方长时间单向通信时，排序会开始和直觉打架。
   */
  observe(remoteTs: number): void {
    if (!Number.isFinite(remoteTs) || remoteTs <= 0) return
    const remoteMs = physicalMs(remoteTs)
    const remoteSeq = remoteTs % SEQ_LIMIT

    if (remoteMs > this.lastMs) {
      // 对方走在我前面：把本地的**毫秒和序号一起**推过去，而不是只推毫秒。
      //
      // 只推毫秒（序号归零）会漏掉这种情况：对方在 12:00:00.000 这一毫秒里
      // 已经排到第 7 条了，我推过去之后自己的下一条是第 1 条 ——
      // 于是「我回复他」的那条时间戳**小于**被回复的那条。
      // 排序上就是回复跑到了原消息前面，而时间戳本身看着完全正常。
      this.lastMs = remoteMs
      this.seq = remoteSeq
    } else if (remoteMs === this.lastMs && remoteSeq > this.seq) {
      // 同一毫秒：把自己的序号推到对方之后，保证之后发的事件排在它后面。
      this.seq = remoteSeq
    } else {
      // 对方更慢：什么都不做 —— 追上去只会把本地时钟往回调，破坏单调性。
      return
    }

    this.last = this.lastMs * SEQ_LIMIT + this.seq
  }
}
