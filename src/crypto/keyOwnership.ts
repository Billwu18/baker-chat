/**
 * 「谁有资格给我发这个会话的钥匙？」
 *
 * 规则只有一条：**成员 id 里最小的那个**（建钥人）。这是每个人都能自己算出来的
 * 确定性规则，所以不需要相信对端说的任何话 —— 也正因如此，这条判断必须待在一个
 * 能被单独测到的地方。
 *
 * 它以前散在 `chatStore.acceptKey` 里、只有两个出口（收 / 拒），于是漏掉了第三种
 * 情况：**建钥人换人了**（id 最小的那个成员退了，或者新进来一个更小的）。那时
 * 日志里躺着的还是旧建钥人发的包 —— 收下就是被抢注，拒掉就是新 owner 永久卡死
 * （拿不到旧钥匙、也建不了新钥匙，会话双向全哑、全程零报错）。
 *
 * 把这条规则抽出来单独放，是因为它既安全关键、又是**唯一**不依赖对端状态的那道
 * 闸门；它一旦写错或者少一个出口，外面看不出来 —— 正常对端本来就会通过。
 */
export type KeySourceVerdict =
  /** 发件人就是建钥人，可以收。 */
  | 'accept'
  /** 建钥人换成本机了：不能收这份（形状上就是抢注），但本机该去建一把新的。 */
  | 'stale_owner'
  /** 拒收，并且本机也不该自己建（等真正的建钥人铺好）。 */
  | 'reject'

export function judgeKeySource(input: {
  /** 本机按规则算出来的建钥人；算不出来（会话还没折进本地状态）时是 null。 */
  owner: string | null
  selfId: string
  senderId: string
}): KeySourceVerdict {
  const { owner, selfId, senderId } = input

  // `owner` 为 null 只有一种情况：这个会话还没折进本地状态，那时既算不出建钥人
  // 也算不出成员，**不能当作「没有规则要守」放行** —— 攻击者恰好能制造这个时机
  // （同步批次里 key 事件先于 session 事件到达是合法的）。
  if (!owner || senderId !== owner) {
    // 建钥人换到了本机：这是正常的名册变动，不是攻击。给出这个信号，让上层去建
    // 一把**更高版本**的钥匙（对端对更高版本是会收的），而不是原地卡死。
    return owner && selfId === owner ? 'stale_owner' : 'reject'
  }

  return 'accept'
}
